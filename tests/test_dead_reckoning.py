"""Pose integrated from proprioception only, so the visit ring is not privileged.

The ring was indexed by the simulator's transform. A real vehicle has GPS and
an IMU, so having a pose is not the cheat -- having a DRIFT-FREE one is. These
tests pin the integration, the left-handed convention, and that drift is
actually reported rather than hidden.
"""
import numpy as np
import pytest

from vae_nav.dead_reckoning import DeadReckoner, calibrate


def test_straight_line_at_constant_speed():
    """No steering: 10 km/h for 10 steps of 0.1 s is 2.78 m along +x."""
    dr = DeadReckoner(dt=0.1)
    dr.reset()
    for _ in range(10):
        dr.step(speed_kmh=10.0, steer=0.0)
    assert dr.x == pytest.approx(10.0 / 3.6 * 1.0, rel=1e-6)
    assert dr.y == pytest.approx(0.0, abs=1e-9)
    assert dr.yaw == pytest.approx(0.0, abs=1e-9)


def test_stationary_vehicle_does_not_move_or_turn():
    dr = DeadReckoner()
    dr.reset()
    for _ in range(50):
        dr.step(speed_kmh=0.0, steer=0.5)
    assert dr.pos == pytest.approx(np.zeros(2))
    assert dr.yaw == pytest.approx(0.0)


def test_left_handed_convention_forward_is_cos_sin():
    """CARLA: forward = (cos yaw, sin yaw).

    A textbook right-handed integration mirrors the path. That exact error
    already shipped once in this repo's goal block.
    """
    dr = DeadReckoner(dt=0.1)
    dr.reset(yaw=np.pi / 2)                 # facing +y
    dr.step(speed_kmh=36.0, steer=0.0)      # 10 m/s for 0.1 s = 1 m
    assert dr.x == pytest.approx(0.0, abs=1e-9)
    assert dr.y == pytest.approx(1.0, rel=1e-6)


def test_positive_steer_turns_one_way_and_negative_the_other():
    out = {}
    for sign in (+1, -1):
        dr = DeadReckoner(dt=0.1)
        dr.reset()
        for _ in range(10):
            dr.step(speed_kmh=10.0, steer=sign * 0.3)
        out[sign] = dr.yaw
    assert np.sign(out[+1]) == -np.sign(out[-1])
    assert abs(out[+1]) == pytest.approx(abs(out[-1]), rel=1e-6)


def test_yaw_is_wrapped_to_pi():
    """Unwrapped yaw would grow without bound and break every trig call."""
    dr = DeadReckoner(dt=0.1)
    dr.reset()
    for _ in range(500):
        dr.step(speed_kmh=30.0, steer=0.5)
    assert -np.pi <= dr.yaw <= np.pi


def test_heading_integrates_before_translation():
    """Translating on the stale heading lags every turn and bows the path out."""
    dr = DeadReckoner(dt=0.1)
    dr.reset()
    dr.step(speed_kmh=36.0, steer=0.4)
    assert dr.yaw != 0.0
    # Displacement must be along the NEW heading, not the old one.
    disp = dr.pos / np.linalg.norm(dr.pos)
    assert disp[0] == pytest.approx(np.cos(dr.yaw), abs=1e-6)
    assert disp[1] == pytest.approx(np.sin(dr.yaw), abs=1e-6)


def test_only_the_ratio_of_max_steer_to_wheelbase_matters():
    """Which is why calibrate() fits ONE gain, not two parameters.

    Doubling both leaves the trajectory unchanged at small angles.
    """
    a = DeadReckoner(wheelbase=1.5, max_steer=0.30, dt=0.1)
    b = DeadReckoner(wheelbase=3.0, max_steer=0.60, dt=0.1)
    assert a.yaw_gain == pytest.approx(b.yaw_gain)
    for dr in (a, b):
        dr.reset()
        for _ in range(20):
            dr.step(speed_kmh=10.0, steer=0.1)
    assert a.yaw == pytest.approx(b.yaw, rel=0.02)


def test_perfect_reckoning_has_zero_drift():
    dr = DeadReckoner(dt=0.1)
    dr.reset()
    for _ in range(20):
        dr.step(speed_kmh=10.0, steer=0.0)
    d = dr.drift(dr.pos, dr.yaw)
    assert d["position_m"] == pytest.approx(0.0)
    assert d["heading_rad"] == pytest.approx(0.0)
    assert d["steps"] == 20


def test_drift_is_reported_against_truth():
    dr = DeadReckoner(dt=0.1)
    dr.reset()
    for _ in range(10):
        dr.step(speed_kmh=10.0, steer=0.0)
    d = dr.drift((dr.x + 3.0, dr.y + 4.0), dr.yaw + 0.2)
    assert d["position_m"] == pytest.approx(5.0)
    assert d["heading_rad"] == pytest.approx(0.2)


def test_heading_drift_wraps_the_short_way():
    """A 0.1 rad error across the +-pi boundary is 0.1, not 6.2."""
    dr = DeadReckoner()
    dr.reset(yaw=np.pi - 0.05)
    d = dr.drift(dr.pos, -np.pi + 0.05)
    assert d["heading_rad"] == pytest.approx(0.1, abs=1e-6)


def test_reset_anchors_to_the_true_start_pose():
    """Not cheating: a vehicle knows where it started; drift accrues after."""
    dr = DeadReckoner()
    dr.reset(pos=(12.0, -5.0), yaw=0.7)
    assert dr.pos == pytest.approx(np.array([12.0, -5.0]))
    assert dr.yaw == pytest.approx(0.7)


# -- calibration ----------------------------------------------------------

def synth_trace(gain, n=300, dt=0.1, seed=0):
    """Ground-truth trace generated by the small-angle model itself."""
    rng = np.random.default_rng(seed)
    v_kmh = rng.uniform(5.0, 25.0, n)
    steer = rng.uniform(-0.4, 0.4, n)
    yaw = np.zeros(n)
    for i in range(1, n):
        yaw[i] = yaw[i - 1] + gain * (v_kmh[i - 1] / 3.6) * steer[i - 1] * dt
    return v_kmh, steer, yaw


def test_calibrate_recovers_a_known_gain():
    v, s, yaw = synth_trace(gain=0.81)
    out = calibrate(v, s, yaw)
    assert out["yaw_gain"] == pytest.approx(0.81, rel=0.02)
    assert out["residual_std"] < 1e-6
    assert out["n"] > 250


def test_calibrate_reports_residual_so_a_bad_fit_is_visible():
    """A silently-applied bad gain would manufacture drift and look like physics."""
    v, s, yaw = synth_trace(gain=0.81)
    yaw = yaw + np.random.default_rng(1).normal(0, 0.05, yaw.size)
    out = calibrate(v, s, yaw)
    assert out["residual_std"] > 0.1


def test_calibrate_unwraps_before_differencing():
    """Every wrap at +-pi would otherwise become a huge fake yaw rate.

    Needs SUSTAINED turning: random steering averages out and never
    accumulates past pi, so a random trace never wraps and would test nothing.
    """
    gain, dt, n = 1.5, 0.1, 400
    v_kmh = np.full(n, 20.0)
    steer = np.full(n, 0.3)                 # constant-sign: the car circles
    yaw = np.zeros(n)
    for i in range(1, n):
        yaw[i] = yaw[i - 1] + gain * (v_kmh[i - 1] / 3.6) * steer[i - 1] * dt

    wrapped = np.arctan2(np.sin(yaw), np.cos(yaw))
    assert np.abs(np.diff(wrapped)).max() > 3.0, "trace must actually wrap"
    assert calibrate(v_kmh, steer, wrapped)["yaw_gain"] == pytest.approx(
        gain, rel=0.05)

    # And the failure it guards: differencing the WRAPPED signal directly.
    naive_rate = np.diff(wrapped) / dt
    x = (v_kmh / 3.6 * steer)[:-1]
    naive_gain = float(np.sum(x * naive_rate) / np.sum(x ** 2))
    assert abs(naive_gain - gain) > 0.1, (
        "without unwrapping the fit should be visibly wrong")


def test_calibrate_refuses_a_trace_with_no_turning():
    """The gain is unidentifiable from straight-line driving."""
    with pytest.raises(ValueError):
        calibrate([10.0] * 50, [0.0] * 50, [0.0] * 50)


def test_calibrate_needs_enough_samples():
    with pytest.raises(ValueError):
        calibrate([10.0], [0.1], [0.0])
